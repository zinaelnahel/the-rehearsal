// Requires a local frontend connected to a demo backend with FEEDBACK_ENABLED=true.
// Makes no provider calls. Use an isolated FEEDBACK_DB_PATH for the test server.
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE?pathToFileURL(process.env.PLAYWRIGHT_MODULE).href:'playwright');
const origin=process.env.FEEDBACK_TEST_URL||'http://127.0.0.1:3019';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[],writes=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(request.method()==='PUT'&&request.url().endsWith('/feedback'))writes.push(request.postDataJSON());});
try {
  const config=await (await page.request.get(origin+'/api/config')).json();
  assert.equal(config.mode,'demo','Use a demo backend to avoid provider calls.');
  assert.equal(config.feedback_enabled,true);
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Build my mission'}).click();
  await page.getByRole('button',{name:/Action - start Take/}).click();
  await page.locator('#message').fill('How much is the rent?');
  await page.getByRole('button',{name:'Send message'}).click();
  await page.locator('.message').nth(2).waitFor();
  await page.getByRole('button',{name:/Cut - finish/}).click();
  const review=page.locator('.dialogue-feedback');
  const consent=review.getByRole('checkbox');
  assert.equal(await consent.isChecked(),false);
  await review.getByRole('button',{name:'Unhelpful rehearsal',exact:true}).click();
  await review.getByText('Thanks. Feedback noted for this session.',{exact:true}).waitFor();
  assert.equal(writes.at(-1).share_for_improvement,false);
  await review.getByLabel('Reason (optional)').selectOption('speed');
  await consent.check();
  await review.getByText('Thanks. Your anonymous feedback was saved to help improve the app.',{exact:true}).waitFor();
  assert.equal(writes.at(-1).share_for_improvement,true);
  assert.equal(writes.at(-1).reason,'speed');
  assert.deepEqual(Object.keys(writes.at(-1)).sort(),['frontend_build','rating','reason','share_for_improvement']);
  await page.getByRole('button',{name:'Back to the conversation',exact:true}).click();
  await page.getByRole('button',{name:/Review this take/}).click();
  assert.equal(await consent.isChecked(),true);
  await consent.uncheck();
  await review.getByText('Thanks. Feedback noted for this session.',{exact:true}).waitFor();
  assert.equal(writes.at(-1).share_for_improvement,false);
  await consent.check();
  await review.getByText('Thanks. Your anonymous feedback was saved to help improve the app.',{exact:true}).waitFor();
  await review.getByRole('button',{name:'Clear',exact:true}).click();
  await review.getByText('Feedback cleared, including any shared copy.',{exact:true}).waitFor();
  assert.equal(await consent.isChecked(),false);
  assert.equal(writes.at(-1).rating,null);
  await page.getByLabel('Interface language').selectOption('de');
  await review.getByLabel('Meine anonyme Bewertung teilen, um die App zu verbessern.').waitFor();
  await page.getByLabel('Sprache der Oberfläche').selectOption('es');
  await review.getByLabel('Compartir mi valoración anónima para ayudar a mejorar la aplicación.').waitFor();
  await page.getByLabel('Idioma de la interfaz').selectOption('en');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  if(process.env.FEEDBACK_TEST_SCREENSHOT)await page.screenshot({path:process.env.FEEDBACK_TEST_SCREENSHOT,fullPage:true});
  await page.getByRole('button',{name:'End session & delete data',exact:false}).click();
  await page.getByText('Session deleted on the server.',{exact:false}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: real API opt-in, session-only default, reason, saved consent across navigation, withdrawal, re-share, clear, EN/DE/ES, mobile layout and deletion. No provider calls.');
} finally {await browser.close();}
