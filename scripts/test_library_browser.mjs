 await page.getByText('All saved rehearsals deleted from this browser.',{exact:true}).waitFor();
 assert.equal((await readRecords()).length,0);
 const blocked=await context.newPage();
 await blocked.addInitScript(()=>Object.defineProperty(globalThis,'indexedDB',{configurable:true,get:()=>undefined}));
 await blocked.route('**/api/**',route=>route.fulfill({status:503,body:'{}'}));
 await blocked.goto(origin,{waitUntil:'networkidle'});
