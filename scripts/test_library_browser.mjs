 await page.getByRole('heading',{name:/What if you could/}).waitFor();
 const library=page.locator('.library-panel');await library.locator('summary').first().click();
 await library.getByRole('button',{name:/German practice one/}).click();
 assert.match(await page.locator('.saved-take').innerText(),/How much is the rent/);
 await library.getByLabel('Compare with another rehearsal').selectOption({label:'Spanish practice two · Spanish · Take 1'});
 assert.equal(await page.locator('.saved-take').count(),2);
 await page.getByLabel('Interface language').selectOption('de');
 await page.getByText('Meine gespeicherten Übungen',{exact:false}).waitFor();
 await page.getByLabel('Sprache der Oberfläche').selectOption('es');
 await page.getByText('Mis ensayos guardados',{exact:false}).waitFor();
 await page.getByLabel('Idioma de la interfaz').selectOption('en');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 if(process.env.LIBRARY_TEST_SCREENSHOT)await page.screenshot({path:process.env.LIBRARY_TEST_SCREENSHOT,fullPage:true});
 page.once('dialog',dialog=>dialog.dismiss());
 await page.getByRole('button',{name:'Delete saved rehearsal',exact:true}).first().click();
 assert.equal((await readRecords()).length,2);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Delete saved rehearsal',exact:true}).first().click();
 await page.getByText('Saved rehearsal deleted from this browser.',{exact:true}).waitFor();
 assert.equal((await readRecords()).length,1);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Delete all saved rehearsals',exact:true}).click();
 await page.getByText('All saved rehearsals deleted from this browser.',{exact:true}).waitFor();
 assert.equal((await readRecords()).length,0);
 await page.reload({waitUntil:'networkidle'});
 await page.locator('.library-panel > summary').click();
 await page.getByText('No saved rehearsals yet. Finish a rehearsal and choose to save it.',{exact:true}).waitFor();
 await page.evaluate(()=>new Promise(resolve=>{
  const request=indexedDB.open('the-rehearsal-library',1);
  request.onsuccess=()=>{const db=request.result;const tx=db.transaction('rehearsals','readwrite');tx.objectStore('rehearsals').put({id:'unsupported-version',schemaVersion:999,title:'Unreadable'});tx.oncomplete=()=>{db.close();resolve();};};
 }));
 await page.reload({waitUntil:'networkidle'});
 await page.locator('.library-panel > summary').click();
