// Local UI integration. API responses are mocked; no provider calls are made.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import path from 'node:path';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {chromium}=require(require.resolve('playwright',{paths:[process.cwd(),path.resolve('.runtime/browser')]}));
const base=process.env.SAMPLE_TEST_URL||'http://127.0.0.1:3038';
assert.ok(['127.0.0.1','localhost'].includes(new URL(base).hostname));
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const voiceScript=JSON.parse(readFileSync('samples/audio/family-boundary.es.json','utf8'));
const part=voiceScript.turns[1];
const audioEvidence={id:'2',source:'Fictional voice message',location:'Voice message segment 2',text:part.text,start:part.start,end:part.end,url:'/api/samples/difficult/audio'};
const errors=[],requests=[];
const goals=[{id:'0',text:'Ask a clear question about the source',achieved:false}];
try{
 const context=await browser.newContext();
 await context.route('**/api/**',async route=>{
  const request=route.request(),url=new URL(request.url()).pathname;
  const body=request.postDataJSON();
  requests.push({url,body,method:request.method()});
  if(url==='/api/samples/difficult/audio')return route.fulfill({contentType:'audio/wav',body:readFileSync('samples/audio/family-boundary.es.wav')});
  let result;
  if(url==='/api/config')result={mode:'demo',speech_enabled:false,vector_store:'memory'};
  else if(request.method()==='DELETE')result={deleted:true};
  else if(url==='/api/sessions')result={id:'sample-test',name:'Sample source',source_url:body.video_url||null};
  else if(url.endsWith('/mission'))result={scenario:body.scenario==='auto'?'difficult':body.scenario,safety:false,goals};
  else if(url.endsWith('/start'))result={turns:[{id:'opening',role:'assistant',content:'You said you already told the others. [2]',sources:[audioEvidence]}],goals,safety:false};
  else if(url.endsWith('/source/2'))result={kind:'transcript',focus:audioEvidence,sections:[{location:audioEvidence.location,text:part.text,selected:true}],original_audio_url:'/api/samples/difficult/audio',audio_timed:true};
  else throw Error('Unexpected API call: '+url);
  await route.fulfill({json:result});
 });
 const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
 await page.goto(base);
 await page.getByRole('button',{name:'Build my mission'}).waitFor();
 await page.getByRole('button',{name:/Celonis/}).click();
 assert.match(await page.locator('.sample-list > .sample').filter({hasText:'Celonis'}).innerText(),/8 pages.*Real PDF/s);

 assert.equal(await page.locator('.sample-list > .sample').filter({hasText:'Habla con E'}).count(),1);
 await page.getByRole('link',{name:/^View original PDF/}).waitFor();
 assert.equal(await page.getByRole('link',{name:/^View original PDF/}).getAttribute('href'),'/api/samples/interview/document');
 assert.equal(await page.locator('.sample-list > .sample').count(),3);
 assert.equal(await page.getByRole('button',{name:/University of Kent|Instituto Cervantes/}).count(),0);
 await page.getByRole('button',{name:'Build my mission'}).click();
 await page.getByRole('heading',{name:'Your conversation checklist'}).waitFor();
 assert.equal(requests.find(r=>r.url==='/api/sessions').body.sample,'interview');
 assert.equal(requests.find(r=>r.url.endsWith('/mission')).body.scenario,'interview');

 await page.goto(base);requests.length=0;
 await page.getByRole('button',{name:/Saying no to family/}).click();
 assert.equal(await page.getByRole('link',{name:/^View original PDF/}).count(),0);
 assert.equal(await page.locator('#language').inputValue(),'Spanish');
 assert.equal(await page.locator('audio').getAttribute('src'),'/api/samples/difficult/audio');
 await page.locator('audio').evaluate(audio=>audio.play());
 await page.waitForFunction(()=>document.querySelector('audio').currentTime>0);
 assert.ok(await page.locator('audio').evaluate(audio=>audio.duration>20&&audio.duration<40));
 await page.locator('audio').evaluate(audio=>audio.pause());
 await page.getByRole('button',{name:'Build my mission'}).click();
 await page.getByRole('alert').filter({hasText:'Review and confirm the audio sample transcript first.'}).waitFor();
 assert.equal(requests.some(r=>r.url==='/api/sessions'),false);
 const reviewed=await page.locator('#sample-audio-transcript').inputValue();
 await page.getByRole('checkbox',{name:'I reviewed this audio transcript and want to use it for my rehearsal.'}).check();
 await page.locator('#sample-audio-transcript').fill(reviewed+'\n');
 assert.equal(await page.getByRole('checkbox',{name:'I reviewed this audio transcript and want to use it for my rehearsal.'}).isChecked(),false);
 await page.getByRole('checkbox',{name:'I reviewed this audio transcript and want to use it for my rehearsal.'}).check();
 await page.getByRole('button',{name:'Build my mission'}).click();
 await page.getByRole('heading',{name:'Your conversation checklist'}).waitFor();
 assert.equal(requests.find(r=>r.url==='/api/sessions').body.sample,'difficult');
 assert.equal(requests.find(r=>r.url==='/api/sessions').body.sample_audio_text,reviewed+'\n');
 assert.equal(requests.find(r=>r.url==='/api/sessions').body.transcript_confirmed,true);
 await page.getByRole('button',{name:/^Action - start/}).click();
 await page.getByRole('button',{name:'View source [2]',exact:true}).click();
 await page.getByRole('button',{name:'Play this excerpt',exact:true}).waitFor();
 await page.getByRole('button',{name:'Play this excerpt',exact:true}).click();
 const excerpt=page.locator('dialog .source-audio audio');
 await page.waitForFunction(start=>{const audio=document.querySelector('dialog .source-audio audio');return audio&&!audio.paused&&audio.currentTime>start;},part.start);
 assert.ok(await excerpt.evaluate((audio,end)=>audio.currentTime<end,part.end));
 await excerpt.evaluate((audio,end)=>{audio.currentTime=end+0.05;audio.dispatchEvent(new Event('timeupdate'));},part.end);
 await page.waitForFunction(()=>document.querySelector('dialog .source-audio audio')?.paused);
 await page.getByRole('button',{name:'Close source',exact:true}).click();

 await page.goto(base);requests.length=0;
 await page.getByRole('tab',{name:'Your situation',exact:true}).click();
 assert.equal(await page.locator('#scenario').inputValue(),'auto');
 assert.equal(await page.locator('#goal').inputValue(),'');
 await page.locator('#document').fill('I am ending my relationship. My decision is final.');
 await page.getByRole('button',{name:'Build my mission'}).click();
 await page.getByRole('heading',{name:'Your conversation checklist'}).waitFor();
 const mission=requests.find(r=>r.url.endsWith('/mission')).body;
 assert.equal(mission.scenario,'auto');assert.equal(mission.goal,'');
 await page.locator('.scene-card').getByRole('heading',{name:'A difficult conversation',exact:true}).waitFor();

 await page.goto(base);requests.length=0;
 await page.getByRole('button',{name:/Habla con E/}).click();
 assert.equal(await page.locator('#language').inputValue(),'Spanish');
 assert.equal(await page.locator('#level').inputValue(),'B2');
 assert.equal(await page.getByRole('button',{name:'Import video transcript',exact:true}).count(),0);
 await page.getByRole('link',{name:/^Watch the flat viewing/}).waitFor();
 assert.equal(requests.some(r=>r.url.includes('/video/')),false);
 await page.getByText('Check captions with video timestamps',{exact:true}).click();
 assert.ok(await page.locator('.transcript-editor details a[href*="&t="]').count()>20);
 const videoText=await page.locator('#sample-video-transcript').inputValue();
 assert.match(videoText,/alquiler/);
 const confirmation=page.getByRole('checkbox',{name:'I reviewed this transcript and want to use it as my source.'});
 await confirmation.check();
 await page.locator('#sample-video-transcript').fill(videoText+'\n');
 assert.equal(await confirmation.isChecked(),false);
 await confirmation.check();
 await page.getByRole('button',{name:'Build my mission'}).click();
 await page.getByRole('heading',{name:'Your conversation checklist'}).waitFor();
 const video=requests.find(r=>r.url==='/api/sessions').body;
 assert.equal(video.video_url,'');
 assert.equal(video.transcript_confirmed,true);
 assert.equal(video.sample,undefined);
 assert.equal(requests.find(r=>r.url.endsWith('/mission')).body.scenario,'apartment');
 assert.equal(video.sample_video_text,videoText+'\n');
 assert.deepEqual(errors,[]);
 console.log('Real PDF picker, custom routing and video review flow passed.');
}finally{await browser.close();}
